import { createHash } from 'node:crypto'
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, posix, relative, resolve, sep } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const CACHE_PREFIX = 'fylde8ball-'

const ROOT_PRECACHE_FILES = new Set([
  'index.html',
  'favicon.svg',
  'manifest.webmanifest',
  'apple-touch-icon.png',
])

function walkFiles(dir, baseDir = dir) {
  if (!existsSync(dir)) return []
  const results = []
  for (const entry of readdirSync(dir)) {
    const full = resolve(dir, entry)
    const stat = statSync(full)
    if (stat.isDirectory()) {
      results.push(...walkFiles(full, baseDir))
    } else {
      const rel = relative(baseDir, full).split(sep).join(posix.sep)
      results.push(rel)
    }
  }
  return results.sort()
}

export function selectPrecacheUrls(relativeFiles) {
  const urls = new Set()

  for (const rel of relativeFiles) {
    if (rel === 'index.html') {
      urls.add('/')
      urls.add('/index.html')
      continue
    }
    if (ROOT_PRECACHE_FILES.has(rel)) {
      urls.add(`/${rel}`)
      continue
    }
    if (rel.startsWith('assets/') || rel.startsWith('icons/')) {
      urls.add(`/${rel}`)
    }
  }

  return Array.from(urls).sort()
}

export function collectPrecacheAssets(distDir) {
  return selectPrecacheUrls(walkFiles(distDir))
}

export function computeCacheVersionFromEntries(entries) {
  const hash = createHash('sha256')
  for (const [url, content] of [...entries].sort((a, b) => a[0].localeCompare(b[0]))) {
    hash.update(url)
    hash.update('\0')
    hash.update(content)
    hash.update('\0')
  }
  return hash.digest('hex').slice(0, 12)
}

export function computeCacheVersion(distDir, precacheUrls) {
  const entries = precacheUrls.map((url) => {
    const rel = url === '/' ? 'index.html' : url.replace(/^\//, '')
    const full = resolve(distDir, rel)
    return [url, existsSync(full) ? readFileSync(full) : '']
  })
  return computeCacheVersionFromEntries(entries)
}

export function buildServiceWorkerSource(cacheName, precacheUrls) {
  return `// Auto-generated by scripts/generate-sw.mjs — do not edit by hand.
const CACHE_PREFIX = ${JSON.stringify(CACHE_PREFIX)}
const CACHE_NAME = ${JSON.stringify(cacheName)}
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)}

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(PRECACHE_URLS))
  )
  self.skipWaiting()
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME)
            .map((key) => caches.delete(key))
        )
      )
      .then(() => self.clients.claim())
  )
})

self.addEventListener('fetch', (event) => {
  const { request } = event
  if (request.method !== 'GET') return

  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return

  // Hashed Vite assets are immutable: cache-first.
  if (url.pathname.startsWith('/assets/')) {
    event.respondWith(
      caches.match(request).then(
        (cached) =>
          cached ||
          fetch(request).then((response) => {
            if (response.ok) {
              const copy = response.clone()
              caches.open(CACHE_NAME).then((cache) => cache.put(request, copy))
            }
            return response
          })
      )
    )
    return
  }

  // Calendar feeds: network-first so subscriptions and downloads stay fresh.
  if (url.pathname.endsWith('.ics')) {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone()
            caches.open(CACHE_NAME).then((cache) => cache.put(request, copy))
          }
          return response
        })
        .catch(() => caches.match(request))
    )
    return
  }

  // Page navigations: network-first with offline fallback to cached page or SPA shell.
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone()
            caches.open(CACHE_NAME).then((cache) => cache.put(request, copy))
          }
          return response
        })
        .catch(() =>
          caches
            .match(request)
            .then((cached) => cached || caches.match('/index.html'))
        )
    )
    return
  }

  // Other same-origin static files (icons, manifest, favicon): stale-while-revalidate.
  event.respondWith(
    caches.match(request).then((cached) => {
      const networkFetch = fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone()
            caches.open(CACHE_NAME).then((cache) => cache.put(request, copy))
          }
          return response
        })
        .catch(() => cached)

      return cached || networkFetch
    })
  )
})
`
}

function main() {
  const __dirname = dirname(fileURLToPath(import.meta.url))
  const root = resolve(__dirname, '..')
  const distDir = resolve(root, 'dist')

  if (!existsSync(distDir)) {
    throw new Error('dist/ directory not found. Run vite-ssg build before generating the service worker.')
  }

  const precacheUrls = collectPrecacheAssets(distDir)
  const version = computeCacheVersion(distDir, precacheUrls)
  const cacheName = `${CACHE_PREFIX}${version}`
  const source = buildServiceWorkerSource(cacheName, precacheUrls)

  writeFileSync(resolve(distDir, 'sw.js'), source, 'utf8')
  console.log(`Generated dist/sw.js — ${cacheName} (${precacheUrls.length} precached assets)`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main()
}
